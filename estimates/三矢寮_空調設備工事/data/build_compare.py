def table(ws, r, title, headers, rows, widths=None, fmts=None):
    ws.cell(r, 1, title).font = FB
    ws.cell(r, 1).fill = SEC
    r += 1
    for i, h in enumerate(headers, 1):
        c = ws.cell(r, i, h); c.font = FB; c.fill = HDR; c.border = B
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    r += 1
    for row in rows:
        for i, v in enumerate(row, 1):
            c = ws.cell(r, i, v); c.font = F; c.border = B
            c.alignment = Alignment(vertical="center", wrap_text=isinstance(v, str))
            if fmts and i - 1 < len(fmts) and fmts[i - 1] and not isinstance(v, str):
                c.number_format = fmts[i - 1]
        r += 1
    return r + 1


